"""Drift test: docs/configuration.md must match the code.

The reference page is generated by hand from ``slotpin.config`` and
``slotpin.dash``; this test fails with a message naming whatever drifted.
``dash.py`` is read as text, never imported (it has import-time side effects).
"""

from __future__ import annotations

import re
from dataclasses import MISSING, fields
from pathlib import Path

import pytest

from slotpin.config import (
    _SCALAR_FIELD_KINDS,
    LEGACY_ENV_ALIASES,
    Config,
    DemoteRule,
    LabelRule,
    LaneRule,
)

ROOT = Path(__file__).resolve().parent.parent
DOC = ROOT / "docs" / "configuration.md"
DASH_SRC = ROOT / "src" / "slotpin" / "dash.py"

STRUCTURED = {"lanes", "demote", "labels"}


def render_default(value: object) -> str:
    """The one rendering rule used by the docs (see docs/configuration.md)."""
    if value is None:
        return "`null`"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, str):
        return f'`"{value}"`'
    if isinstance(value, Path):
        return f"`{value}`"
    if isinstance(value, list):
        assert value == [], "list defaults are documented as []"
        return "`[]`"
    return f"`{value!r}`"  # int / float


def _cells(line: str) -> list[str]:
    return [c.strip() for c in line.strip().strip("|").split("|")]


def _section(text: str, heading: str) -> list[str]:
    """Lines under ``## heading`` up to the next ``## `` heading."""
    lines = text.splitlines()
    start = next(
        (i for i, ln in enumerate(lines) if ln.strip() == f"## {heading}"), None
    )
    assert start is not None, f"docs/configuration.md has no '## {heading}' section"
    out: list[str] = []
    for ln in lines[start + 1 :]:
        if ln.startswith("## "):
            break
        out.append(ln)
    return out


def _table_rows(lines: list[str]) -> list[list[str]]:
    rows = []
    for ln in lines:
        if ln.startswith("| `"):
            rows.append(_cells(ln))
    return rows


@pytest.fixture(scope="module")
def doc_text() -> str:
    return DOC.read_text(encoding="utf-8")


@pytest.fixture(scope="module")
def main_rows(doc_text: str) -> dict[str, list[str]]:
    """Rows of the main table (the one headed ``| TOML key |``), keyed by TOML key."""
    rows: dict[str, list[str]] = {}
    in_main = False
    for ln in doc_text.splitlines():
        if ln.startswith("| TOML key |"):
            in_main = True
            continue
        if not in_main:
            continue
        if not ln.startswith("|"):
            break
        m = re.match(r"^\| `([^`]+)` \|", ln)
        if m:
            rows[m.group(1)] = _cells(ln)
    assert rows, "docs/configuration.md has no main table headed '| TOML key |'"
    return rows


def test_documented_keys_match_config_fields(main_rows: dict[str, list[str]]) -> None:
    documented = set(main_rows)
    actual = {f.name for f in fields(Config)}
    assert documented == actual, (
        f"docs/configuration.md main table drifted from Config: "
        f"missing from docs={sorted(actual - documented)} "
        f"documented but not in Config={sorted(documented - actual)}"
    )


def test_every_scalar_field_has_a_kind() -> None:
    scalar = {f.name for f in fields(Config)} - STRUCTURED
    assert scalar == set(_SCALAR_FIELD_KINDS), (
        "Config scalar fields and _SCALAR_FIELD_KINDS differ: "
        f"{sorted(scalar ^ set(_SCALAR_FIELD_KINDS))}"
    )


def test_documented_defaults_match_code(main_rows: dict[str, list[str]]) -> None:
    cfg = Config()
    for f in fields(Config):
        row = main_rows.get(f.name)
        assert row is not None, f"{f.name} missing from docs table"
        expected = render_default(getattr(cfg, f.name))
        assert row[3] == expected, (
            f"default drift for '{f.name}': docs say {row[3]}, code default renders as {expected}"
        )
        # every field must have a default (the doc has one column for it)
        assert f.default is not MISSING or f.default_factory is not MISSING


def test_env_vars_documented(main_rows: dict[str, list[str]]) -> None:
    for f in fields(Config):
        env_cell = main_rows[f.name][1]
        if f.name in STRUCTURED:
            assert "TOML only" in env_cell, (
                f"'{f.name}' is TOML-only; docs env column should say so, got {env_cell!r}"
            )
            continue
        expected = f"SLOTPIN_{f.name.upper()}"
        names = re.findall(r"`(SLOTPIN_[A-Z0-9_]+)`", env_cell)
        assert names and names[0] == expected, (
            f"env var drift for '{f.name}': docs list {names}, expected first entry {expected}"
        )
        for alias, target in LEGACY_ENV_ALIASES.items():
            if target == f.name:
                assert alias in names, (
                    f"legacy alias {alias} for '{f.name}' is not mentioned in its docs row"
                )


def _class_default_cell(f) -> str:
    if f.default is not MISSING:
        return render_default(f.default)
    if f.default_factory is not MISSING:  # type: ignore[misc]
        return render_default(f.default_factory())  # type: ignore[misc]
    return "required"


@pytest.mark.parametrize(
    ("heading", "cls"),
    [
        ("`[[classify.lanes]]` fields", LaneRule),
        ("`[[classify.demote]]` fields", DemoteRule),
        ("`[[classify.labels]]` fields", LabelRule),
    ],
)
def test_classify_tables(doc_text: str, heading: str, cls: type) -> None:
    rows = {r[0].strip("`"): r for r in _table_rows(_section(doc_text, heading))}
    actual = {f.name for f in fields(cls)}
    assert set(rows) == actual, (
        f"{heading} drifted from {cls.__name__}: "
        f"missing from docs={sorted(actual - set(rows))} "
        f"documented but not a field={sorted(set(rows) - actual)}"
    )
    for f in fields(cls):
        doc_default = rows[f.name][2].strip()
        expected = _class_default_cell(f)
        assert doc_default == expected, (
            f"{heading}: default drift for '{f.name}': docs say {doc_default}, "
            f"code says {expected}"
        )


def test_dashboard_env_vars(doc_text: str) -> None:
    src = DASH_SRC.read_text(encoding="utf-8")
    in_code = set(re.findall(r"DASH_[A-Z_]+", src))
    rows = _table_rows(_section(doc_text, "Dashboard environment variables"))
    documented = {r[0].strip("`") for r in rows}
    assert documented == in_code, (
        "dashboard env var drift between dash.py and docs/configuration.md: "
        f"read by dash.py but undocumented={sorted(in_code - documented)} "
        f"documented but unknown to dash.py={sorted(documented - in_code)}"
    )
